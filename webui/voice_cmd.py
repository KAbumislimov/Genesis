#!/usr/bin/env python3.11
"""Campus Voice Assistant — Whisper STT + Claude AI + edge-tts TTS
Campus commands (stop/next/volume) are executed immediately;
all responses generated by Claude for natural, intelligent replies.
"""
import os, sys, subprocess, tempfile, json, re, datetime, random, urllib.parse, threading

STATE_FILE = os.path.join(tempfile.gettempdir(), 'campus-voice-game-state.json')

WHISPER_MODEL = None

def _ollama_warmup():
    """Pre-load Ollama model into RAM so first user request is fast."""
    model = os.environ.get('OLLAMA_MODEL', '')
    host  = os.environ.get('OLLAMA_HOST', 'http://host.docker.internal:11434')
    if not model:
        return
    try:
        import urllib.request
        body = json.dumps({'model': model, 'keep_alive': '10m'}).encode()
        req = urllib.request.Request(f'{host}/api/generate', data=body,
            headers={'Content-Type': 'application/json'}, method='POST')
        with urllib.request.urlopen(req, timeout=120) as r:
            r.read()
    except Exception:
        pass

threading.Thread(target=_ollama_warmup, daemon=True).start()

def _load_model():
    global WHISPER_MODEL
    if WHISPER_MODEL is None:
        from faster_whisper import WhisperModel
        cache = os.path.join(os.environ.get('HF_HOME', os.path.expanduser('~/.cache')), 'faster_whisper')
        WHISPER_MODEL = WhisperModel('base', device='cpu', compute_type='int8', download_root=cache)
    return WHISPER_MODEL

def transcribe(audio_path: str) -> str:
    wav = audio_path
    if not audio_path.endswith('.wav'):
        wav = tempfile.mktemp(suffix='.wav')
        try:
            subprocess.run(
                ['ffmpeg', '-y', '-i', audio_path, '-ar', '16000', '-ac', '1', wav],
                capture_output=True, timeout=30
            )
        except Exception as e:
            return f'[ffmpeg error: {e}]'
    try:
        model = _load_model()
        segs, _ = model.transcribe(wav, beam_size=3)
        return ' '.join(s.text.strip() for s in segs).strip()
    except Exception as e:
        return f'[whisper error: {e}]'
    finally:
        if wav != audio_path and os.path.exists(wav):
            os.unlink(wav)

# ── Campus API helper ─────────────────────────────────────────────────────────
def _api(path, method='POST', data=None):
    import urllib.request
    url = f'http://localhost:8090{path}'
    body = json.dumps(data or {}).encode()
    req = urllib.request.Request(url, data=body,
                                  headers={'Content-Type': 'application/json'}, method=method)
    try:
        with urllib.request.urlopen(req, timeout=5) as r:
            return json.loads(r.read())
    except Exception:
        return {}

# ── Real-time data fetchers ───────────────────────────────────────────────────
def _fetch_weather(city: str = 'Baku') -> str:
    try:
        import urllib.request
        url = f'http://wttr.in/{urllib.parse.quote(city)}?format=j1'
        with urllib.request.urlopen(url, timeout=5) as r:
            d = json.loads(r.read())
        cur = d['current_condition'][0]
        desc = (cur.get('weatherDesc') or [{}])[0].get('value', '')
        return f"{cur['temp_C']}°C, ощущается {cur['FeelsLikeC']}°C, {desc}, влажность {cur['humidity']}%"
    except Exception:
        return ''

def _extract_city(t: str) -> str:
    """'погода в москве' -> 'Москва'. Пусто, если город не указан явно (тогда Баку)."""
    m = re.search(r'погод[а-я]*\s+в\s+([а-яё\-\s]+)', t)
    if not m:
        m = re.search(r'weather\s+in\s+([a-z\-\s]+)', t)
    if m:
        return m.group(1).strip().rstrip('?.!').title()
    return ''

def _fetch_wikipedia(query: str) -> str:
    try:
        import urllib.request
        url = f'https://ru.wikipedia.org/api/rest_v1/page/summary/{urllib.parse.quote(query)}'
        req = urllib.request.Request(url, headers={'User-Agent': 'campus-voice-assistant/1.0'})
        with urllib.request.urlopen(req, timeout=6) as r:
            d = json.loads(r.read())
        return (d.get('extract') or '').strip()
    except Exception:
        return ''

def _fetch_track() -> str:
    d = _api('/api/status', method='GET')
    return d.get('track') or d.get('title') or d.get('playing') or ''

# ── Keyword maps (for immediate campus actions) ───────────────────────────────
